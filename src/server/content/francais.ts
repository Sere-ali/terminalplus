FRANCAIS["temps-verbaux"] = String.raw`## 💡 L'essentiel en une phrase
Les **temps verbaux** se répartissent en deux **systèmes** : le **récit** (histoire racontée à distance) et le **discours** (situation d'énonciation vécue).

## 📚 1. Les deux systèmes

| | **Système du récit** | **Système du discours** |
|---|---|---|
| Temps de base | passé simple (*il partit*) | présent (*il part*) |
| Arrière-plan | imparfait (*il pleuvait*) | passé composé (*il est parti*) |
| Antériorité | plus-que-parfait | passé composé / futur antérieur |
| Après | conditionnel présent (futur du passé) | futur simple |
| Marqueurs | *la veille*, *le lendemain* | *hier*, *demain* |

## 🧩 2. Valeurs
- **Imparfait** : description, durée, habitude. **Passé simple** : action brève, achevée au premier plan.
- **Présent** : actuel, habitude, **vérité générale**, **historique** (rend le récit vivant).
- **Passé composé** : action accomplie dont on voit le résultat.
- **Mode** : indicatif (fait réel), subjonctif (souhait), conditionnel (hypothèse), impératif (ordre). **Aspect** : accompli/inaccompli.

## 📊 3. Conjugaison à maîtriser

| Temps | Formation | Exemple (verbe *finir*) |
|---|---|---|
| **Passé simple** | radical + -is, -is, -it, -îmes, -îtes, -irent | il **finit**, ils **finirent** |
| **Imparfait** | radical + -ais, -ais, -ait, -ions, -iez, -aient | il **finissait** |
| **Plus-que-parfait** | auxiliaire à l'imparfait + participe passé | il **avait fini** |
| **Futur antérieur** | auxiliaire au futur + participe passé | il **aura fini** |
| **Conditionnel présent** | radical du futur + terminaisons de l'imparfait | il **finirait** |

## 🧪 4. Exemple de lecture
« *Il frappa à la porte. Personne ne répondit. La nuit tombait ; une pluie fine mouillait la rue.* »
- **Frappa, répondit** (passé simple) : actions de premier plan, successives.
- **Tombait, mouillait** (imparfait) : décor, arrière-plan.

## ✏️ Exercices
**Exercice 1.** Mets au passé simple : « Il ouvre la porte et sort. »

:::corrige
Il **ouvrit** la porte et **sortit**.
:::

**Exercice 2.** Quel est l'effet du **présent de narration** ?

:::corrige
Il rend la scène **vivante** et actuelle, comme si le lecteur la voyait.
:::

**Exercice 3.** Quelle valeur a l'imparfait dans : « Chaque matin, il allait au marché » ?

:::corrige
**Valeur d'habitude** (répétition dans le passé).
:::

## 🏆 À retenir pour le BAC
Ne mélange pas les **deux systèmes** dans un même passage sans **raison stylistique**.`

FRANCAIS["rythme"] = String.raw`## 💡 L'essentiel en une phrase
Le **rythme** est la manière dont le texte **s'écoule** (accents, pauses, groupes) ; il **renforce le sens**.

## 📚 1. Dans le vers
- **Accents et coupes** (césure à l'hémistiche pour l'alexandrin : 6 + 6).
- **Rimes**, **sonorités**.
- Effets : rythme **régulier** ou **irrégulier**, **fluide** ou **heurté**, **rejet** (mot rejeté au vers suivant), **contre-rejet**.

## 📚 2. Dans la prose
- **Accents et pauses**, **groupes syntaxiques**.
- **Rythme binaire** (deux éléments), **ternaire** (trois : ampleur), **croissant** (groupes de plus en plus longs : amplification), **décroissant**.
- **Ponctuation** : virgules, points de suspension.

## ✍️ Méthode
Repérer **les accents et les coupes**, décrire le rythme, puis **l'interpréter** (vitesse, calme, colère, solennité).

## 🧪 3. Exemples
- **Rythme ternaire** : « Il est venu, il a vu, il a vaincu. » (ampleur, rapidité).
- **Rythme croissant** : « Il court, il court vers le village qui l'attend. » (élan).
- **Rythme heurté** : « Il tombe. Se relève. Retombe. » (effort, souffrance).

## 📊 4. Alexandrin : repérage

| Élément | Description |
|---|---|
| **Hémistiche** | Chaque moitié du vers (6 syllabes) |
| **Césure** | Pause après la 6ᵉ syllabe |
| **Rejet** | Mot placé au vers suivant, mis en valeur |
| **Contre-rejet** | Mot placé à la fin du vers précédent, en valeur |

## ✏️ Exercices
**Exercice 1.** Quel rythme dans : « Il courut, tomba, se releva, s'enfuit » ?

:::corrige
Rythme **rapide** et **saccadé** (énumération de verbes d'action) : l'urgence de la fuite.
:::

**Exercice 2.** Que produit la ponctuation par points de suspension ?

:::corrige
Un **suspens**, une **hésitation**, un silence chargé d'émotion.
:::

## 🏆 À retenir pour le BAC
Relier **toujours** le rythme au **sens** et à l'**émotion**.`

